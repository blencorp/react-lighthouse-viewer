import {
  isLighthouseReport,
  type LighthouseReport,
  type ReportSource,
  type SrcSource,
  type UrlSource,
} from '@blen/react-lighthouse-viewer';

export type SampleSummary = {
  slug: string;
  thumbnail: string | null;
  url: string;
  lighthouseVersion: string;
  fetchTime: string;
  scores: { id: string; title: string; score: number | null }[];
};

/** What the viewer shows: a title, and the source props for `<LighthouseViewer>`. */
export type View = { key: string; title: string; source: UrlSource | SrcSource | ReportSource };

export const reportsUrl = `${import.meta.env.BASE_URL}reports/`;

// Set VITE_PAGESPEED_API_KEY in example/.env.local (see docs/pagespeed-api-key.md).
const pageSpeedApiKey: string | undefined = import.meta.env['VITE_PAGESPEED_API_KEY'];

// The sample reports are generated by `pnpm reports` (and on every Pages deploy), so they are
// always fresh runs of the bundled Lighthouse version. The dev server answers a missing file with
// its HTML page, so a failed request or a parse error both mean "no samples".
export async function loadIndex(): Promise<SampleSummary[]> {
  try {
    const response = await fetch(`${reportsUrl}index.json`);
    return response.ok ? await response.json() : [];
  } catch {
    return [];
  }
}

const sampleViews = new Map<string, View>();

// One object per sample, so React sees the same view when the same sample is selected again.
export function sampleView(slug: string, title: string): View {
  let view = sampleViews.get(slug);
  if (!view) {
    view = { key: slug, title, source: { src: `${reportsUrl}${encodeURIComponent(slug)}.json` } };
    sampleViews.set(slug, view);
  }
  return view;
}

/** A website to analyze, or the URL of a saved `.json` report. */
export function addressView(address: string): View {
  return /\.json([?#].*)?$/i.test(address)
    ? { key: `src:${address}`, title: address, source: { src: address } }
    : {
        key: `url:${address}`,
        title: address,
        source: { url: address, ...(pageSpeedApiKey ? { apiKey: pageSpeedApiKey } : {}) },
      };
}

export function fileView(file: File): View {
  return {
    key: `file:${file.name}:${file.lastModified}`,
    title: file.name,
    source: { report: readReport(file) },
  };
}

async function readReport(file: File): Promise<LighthouseReport> {
  let json: unknown;
  try {
    json = JSON.parse(await file.text());
  } catch {
    throw new Error(`${file.name} is not valid JSON.`);
  }
  if (!isLighthouseReport(json)) throw new Error(`${file.name} is not a Lighthouse JSON report.`);
  return json;
}

export function hostOf(url: string) {
  return new URL(url).hostname.replace(/^www\./, '');
}
